//! Exact adaptive residue search with an independently recomputed Lean count.
use collatz_search::pinned_lean_toolchain;
use collatz_search::residue::{ResidueSummary, explore};
use serde_json::json;
use sha2::{Digest, Sha256};
use std::{env, fs, path::PathBuf, process::Command, time::Instant};

const ROOT: &str = env!("CARGO_MANIFEST_DIR");
const AFFINE: &str = include_str!("../../CollatzAffine.lean");
const CHECKER: &str = include_str!("../../lean/ResidueSieveBody.lean");

struct Options {
    depth: u32,
    budget: u64,
    verify: bool,
    output: PathBuf,
    certificate: PathBuf,
}

fn options() -> Result<Option<Options>, String> {
    let mut opts = Options {
        depth: 24,
        budget: 5_000_000,
        verify: false,
        output: PathBuf::from(ROOT).join("results"),
        certificate: PathBuf::from(ROOT).join("CollatzResidueCerts.lean"),
    };
    let mut args = env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--depth" => {
                opts.depth = args
                    .next()
                    .ok_or("--depth needs an integer")?
                    .parse()
                    .map_err(|_| "--depth must be an integer from 0 to 63")?;
            }
            "--node-budget" => {
                opts.budget = args
                    .next()
                    .ok_or("--node-budget needs an integer")?
                    .parse()
                    .map_err(|_| "--node-budget must be a positive integer")?;
            }
            "--verify-lean" => opts.verify = true,
            "--output-dir" => opts.output = args.next().ok_or("--output-dir needs a path")?.into(),
            "--certificate" => {
                opts.certificate = args.next().ok_or("--certificate needs a path")?.into()
            }
            "--help" | "-h" => {
                println!(
                    "Adaptive exact Collatz residue search\n\
                    Usage: residue-sieve [--depth N] [--node-budget N] [--verify-lean]\n\
                    [--output-dir DIR] [--certificate FILE]\n\n\
                    Default depth 24, maximum 63; default node budget 5000000.\n\
                    Budget exhaustion is an error; no partial count is exported.\n\
                    A closed class proves descent for every member greater than 1.\n\
                    Open classes remain unresolved. Lean independently recomputes\n\
                    the affine map at every node and checks the closed-class count.\n\
                    Default artifacts: results/residue_sieve_rust.json and CollatzResidueCerts.lean.\n\
                    Pinned Lean toolchain: {}",
                    pinned_lean_toolchain()
                );
                return Ok(None);
            }
            _ => return Err(format!("unknown argument {arg}; use --help")),
        }
    }
    let cwd = env::current_dir().map_err(|e| e.to_string())?;
    if opts.output.is_relative() {
        opts.output = cwd.join(opts.output);
    }
    if opts.certificate.is_relative() {
        opts.certificate = cwd.join(opts.certificate);
    }
    Ok(Some(opts))
}

fn certificate(summary: &ResidueSummary) -> String {
    let depth = summary.max_depth;
    let count = summary.closed_positive_weight_at_max_depth;
    let open = summary.unresolved_weight_at_max_depth;
    format!(
        "/- Generated by the Rust residue-sieve. Numeric counts are independently recomputed. -/
{AFFINE}
{CHECKER}
namespace CollatzResidue
theorem closed_count : countCovered {depth} 0 0 = {count} := by native_decide
theorem count_in_every_block (t : Nat) :
    countWhere (fun r => good {depth} (2 ^ {depth} * t + r)) (2 ^ {depth}) = {count} := by
  exact (count_each_block {depth} t).trans closed_count
theorem open_count : countOpen {depth} 0 0 = {open} := by
  have subtract_count (depth k r c : Nat) (hc : countCovered depth k r = c) :
      countOpen depth k r = 2 ^ depth - c :=
    congrArg (fun x => 2 ^ depth - x) hc
  exact subtract_count {depth} 0 0 {count} closed_count
theorem accepted_starts_descend (n : Nat) (h : good {depth} n = true) (hn : 1 < n) :
    ∃ j, j ≤ {depth} ∧ CollatzAffine.orbit j n < n := good_sound {depth} n h hn
#print axioms closed_count
#print axioms count_in_every_block
#print axioms accepted_starts_descend
end CollatzResidue
"
    )
}

fn resolve(path: &std::path::Path) -> std::io::Result<PathBuf> {
    path.canonicalize().or_else(|_| {
        Ok(path
            .parent()
            .ok_or_else(|| std::io::Error::other("missing parent"))?
            .canonicalize()?
            .join(
                path.file_name()
                    .ok_or_else(|| std::io::Error::other("missing filename"))?,
            ))
    })
}

fn run() -> Result<(), Box<dyn std::error::Error>> {
    let Some(opts) = options()? else {
        return Ok(());
    };
    let start = Instant::now();
    let summary = explore(opts.depth, opts.budget)?;
    let search_seconds = start.elapsed().as_secs_f64();
    let source = certificate(&summary);
    fs::create_dir_all(&opts.output)?;
    if let Some(parent) = opts.certificate.parent() {
        fs::create_dir_all(parent)?;
    }
    let manifest = opts.output.join("residue_sieve_rust.json");
    let logfile = opts.output.join("residue_sieve_rust.log");
    let resolved = resolve(&opts.certificate)?;
    let protected = [
        manifest.clone(),
        logfile.clone(),
        PathBuf::from(ROOT).join("CollatzAffine.lean"),
        PathBuf::from(ROOT).join("lean/ResidueSieveBody.lean"),
    ];
    for path in protected {
        if resolved == resolve(&path)? {
            return Err("--certificate must differ from input templates, manifest, and log".into());
        }
    }
    fs::write(&opts.certificate, &source)?;
    let mut data = json!({
        "schema": 1, "implementation": "Rust",
        "map": "shortcut U(n)=(3*n+1)/2 if odd; n/2 if even",
        "arithmetic": "checked u128; maximum depth 63; abort on overflow or budget exhaustion",
        "coverage": "closed residue classes modulo 2^depth; every member n>1 descends within depth shortcut steps",
        "unresolved": "open classes are not counterexamples and need not fail to descend",
        "certificate_status": "not_run", "certificate_file": opts.certificate,
        "certificate_sha256": format!("{:x}", Sha256::digest(source.as_bytes())),
        "affine_source_sha256": format!("{:x}", Sha256::digest(AFFINE.as_bytes())),
        "checker_source_sha256": format!("{:x}", Sha256::digest(CHECKER.as_bytes())),
        "certified_fields": ["max_depth", "total_residues_at_max_depth", "closed_positive_weight_at_max_depth", "unresolved_weight_at_max_depth"],
        "certificate_trust": "kernel soundness and exact counting proofs; numeric count uses native_decide (Lean compiler and runtime)",
        "diagnostics": "other summary fields are Rust discovery diagnostics, not independently certified",
        "summary": summary, "timings_seconds": {"search": search_seconds}
    });
    let save = |value: &serde_json::Value| -> Result<(), Box<dyn std::error::Error>> {
        fs::write(
            &manifest,
            format!("{}\n", serde_json::to_string_pretty(value)?),
        )?;
        Ok(())
    };
    save(&data)?;
    if opts.verify {
        let toolchain = pinned_lean_toolchain();
        let selector = format!("+{toolchain}");
        eprintln!("Independently recomputing residue coverage with {toolchain}...");
        let clock = Instant::now();
        let checked = Command::new("lean")
            .arg(&selector)
            .arg(&opts.certificate)
            .current_dir(ROOT)
            .output();
        data["timings_seconds"]["lean"] = json!(clock.elapsed().as_secs_f64());
        match checked {
            Ok(output) => {
                let log = format!(
                    "Command: lean {selector} {}\n{}{}",
                    opts.certificate.display(),
                    String::from_utf8_lossy(&output.stdout),
                    String::from_utf8_lossy(&output.stderr)
                );
                fs::write(&logfile, &log)?;
                let proof_ok = collatz_search::lean_proof_succeeded(&output);
                data["certificate_status"] = json!(if proof_ok { "verified" } else { "failed" });
                save(&data)?;
                if !proof_ok {
                    return Err(format!(
                        "Lean rejected the certificate; see {}",
                        logfile.display()
                    )
                    .into());
                }
            }
            Err(error) => {
                data["certificate_status"] = json!("failed");
                data["verification_error"] = json!(error.to_string());
                fs::write(&logfile, format!("Could not run Lean: {error}\n"))?;
                save(&data)?;
                return Err(error.into());
            }
        }
    }
    println!("{}", serde_json::to_string_pretty(&data)?);
    Ok(())
}

fn main() {
    if let Err(error) = run() {
        eprintln!("error: {error}");
        std::process::exit(1);
    }
}
